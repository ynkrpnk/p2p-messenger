#pragma once
#include <cstdint>
#include <string>

// Перелік типів пакетів, які використовуються для обміну даними
enum class PacketType : uint8_t {
    Hello = 1, // Початкове привітання між клієнтом і сервером
    Text = 2,  // Текстове повідомлення
    Ping = 3,  // Запит для перевірки з'єднання
    Pong = 4   // Відповідь на запит Ping
};

// Структура, яка описує мережевий пакет
struct Packet {
    PacketType type; // Тип пакета
    std::string body; // Основний вміст пакета
};

// Розмір заголовка пакета: 1 байт для типу та 4 байти для довжини повідомлення
constexpr size_t HEADER_SIZE = 5;

// Максимально допустимий розмір тіла пакета (1 МБ), використовується для захисту від некоректних даних
constexpr uint32_t MAX_BODY = 1024 * 1024;

// Результати спроби розбору отриманого пакета
enum class ParseResult {
    Ok,        // Пакет успішно отримано та оброблено
    NeedMore,  // Недостатньо даних для повного отримання пакета
    Error      // Під час розбору пакета виникла помилка
};

// Формування пакета для подальшого відправлення
std::string encode_packet(PacketType type, const std::string& body);

// Отримання та розбір одного пакета з початку буфера прийнятих даних
ParseResult try_decode(std::string& buf, Packet& out);

